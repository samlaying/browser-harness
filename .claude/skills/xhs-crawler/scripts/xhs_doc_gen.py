# OCR 水印/噪音行（小红书博主图尾、社区水印），附录里清掉提升可读性
NOISE_LINES = {
    "KKA", "Design", "Bot", "KKA Design Bot", "真知浩见",
    "市场&用户洞察人员专属社区", "Market & User Insight Lab",
    "和Peron一起学用研 👀", "和Peron一起学用研",
}


def clean_ocr(text):
    """轻清洗：去水印噪音行、合并多余空行。不改动实质内容。"""
    if not text:
        return ""
    lines = []
    for ln in text.splitlines():
        s = ln.strip()
        if s in NOISE_LINES:
            continue
        if s.startswith("市场&用户洞察") or s.startswith("Market & User"):
            continue
        lines.append(ln.rstrip())
    out = "\n".join(lines)
    out = re.sub(r'\n{3,}', '\n\n', out)
    return out.strip()


