def main():
    outdir = sys.argv[1]
    enriched = json.load(open(os.path.join(outdir, "notes_enriched.json"), encoding="utf-8"))
    # 原始 JSON 拿链接
    import glob
    nid2url = {}
    for fp in sorted(glob.glob(os.path.join(outdir, "*.json"))):
        if os.path.basename(fp) in ("state.json", "notes_enriched.json", "notes_order.json"):
            continue
        try:
            d = json.load(open(fp, encoding="utf-8"))
            if d.get("note_id"):
                nid2url[d["note_id"]] = "https://www.xiaohongshu.com/explore/%s" % d["note_id"]
        except Exception:
            pass

    parts = [SYNTH]
    for i, n in enumerate(enriched, 1):
        nid = n.get("note_id", "")
        title = n.get("title") or "(无标题)"
        ocr = clean_ocr(n.get("noteImg_ocr") or "")
        url = nid2url.get(nid, "")
        parts.append("\n### [%d] %s\n" % (i, title))
        if url:
            parts.append("源链接：%s\n" % url)
        if ocr:
            parts.append("\n%s\n" % ocr)
        else:
            parts.append("\n*(本篇无图片 OCR 内容：可能为视频帖或正文为主)*\n")

    md = "".join(parts)
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(outdir, "用户访谈·追问技巧整理.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(md)
    print("✓ 生成 %d 字符 → %s" % (len(md), out))


if __name__ == "__main__":
    main()
